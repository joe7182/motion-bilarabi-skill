/** skill/motion-bilarabi/catalog.md: the same list for Claude, with how to write each one. */
export function skillCatalogMd(): string {
  const out: string[] = []
  out.push('<!-- Generated by `npx tsx scripts/catalog.ts` from engine/src/core/catalog.ts — edit that file, not this one. -->')
  out.push('# Effects catalog (names people use → how to write them)', '')
  out.push('People pick effects by their Arabic name (the GitHub page EFFECTS.md shows them with previews).')
  out.push('Match the name loosely (spelling, dialect, English); if two entries fit, ask one short question.')
  out.push('A sentence the user did not assign is yours to design, following the rules in SKILL.md.', '')
  out.push('**The style is a pack:** put `"pack": "<id>"` in `preset.json` — it sets the look, where the headline sits, the key-word mark,')
  out.push('the background, the frame marks, the transitions and the motion feel. Nothing else to add by hand.', '')
  out.push('**Where picks go:** `mba preset` writes `edit.json` from `preset.json` and overwrites it each run. Make every')
  out.push('`preset.json` change first, run `mba preset` once, then put the picks into `edit.json`: replace that')
  out.push("sentence's scene (same start and length, its words timed from `transcript.json`), add a transition")
  out.push('between two scenes. Then `mba validate` (style notes are advice; the person\'s pick stands). Re-running `mba preset` drops the picks.', '')
  out.push('## Style menu (ask before the storyboard)', '')
  out.push('| # | Name | `pack` | Look | Brings |', '|---|---|---|---|---|')
  for (const s of STYLES) out.push(`| ${s.n} | ${s.ar} · ${s.en} | \`${s.id}\` | \`${s.look}\` | ${s.with ? s.with.map((w) => `\`${w}\``).join(', ') : '—'} |`)
  out.push('')
  for (const g of CATALOG_GROUPS) {
    out.push(`## ${GROUP_TITLES[g]}`, '')
    out.push('| Arabic name | Write | User might say |', '|---|---|---|')
    for (const e of CATALOG.filter((x) => x.group === g)) out.push(`| ${e.ar} | ${cell(howToWrite(e))} | ${cell(e.ask)} |`)
    out.push('')
  }
  return out.join('\n')
}
