import { CATALOG, CATALOG_GROUPS, GROUP_TITLES, STYLES, type CatalogEntry } from './catalog'

/** How Claude writes an entry in a storyboard. */
export function howToWrite(e: CatalogEntry): string {
  if (e.use) return e.use
  const [type, variant] = e.id.split(':')
  if (type === 'transition') return `transition \`"type": "${variant}"\``
  if (!variant) return `scene \`"type": "${type}"\``
  if (type === 'arabic-move') return `arabic-move with \`"move": "${variant}"\``
  return `${type} with \`"mode": "${variant}"\``
}

