/**
 * Vendors the Lucide icons the engine uses (ICON_NAMES) into src/runtime/icons/lucide.ts, with the
 * Lucide licence (ISC, plus the Feather MIT notice) as its header comment. Only the named icons
 * are copied; a missing name fails the run.
 *
 *   npx tsx scripts/vendor-icons.ts
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { ICON_NAMES } from '../src/core/params/icon'

const PKG = fileURLToPath(new URL('../node_modules/lucide-static/', import.meta.url))
const OUT = fileURLToPath(new URL('../src/runtime/icons/lucide.ts', import.meta.url))

type Node = [tag: string, attrs: Record<string, string>]

/** The child elements of a lucide-static SVG file, as [tag, attrs] (they are all self-closing). */
export function svgNodes(svg: string): Node[] {
  const body = svg.replace(/<!--[\s\S]*?-->/g, '').replace(/^[\s\S]*?<svg\b[^>]*>/, '').replace(/<\/svg>[\s\S]*$/, '')
  const nodes: Node[] = []
  for (const m of body.matchAll(/<([a-z]+)\b([^>]*?)\/?>/g)) {
    const attrs: Record<string, string> = {}
    for (const a of m[2]!.matchAll(/([a-zA-Z][\w-]*)="([^"]*)"/g)) attrs[a[1]!] = a[2]!
    nodes.push([m[1]!, attrs])
  }
  return nodes
}

function main(): void {
  const version = (JSON.parse(readFileSync(PKG + 'package.json', 'utf8')) as { version: string }).version
  const licence = readFileSync(PKG + 'LICENSE', 'utf8').replace(/\r\n/g, '\n').trim()
  const missing = ICON_NAMES.filter((n) => !existsSync(`${PKG}icons/${n}.svg`))
  if (missing.length) throw new Error(`lucide-static ${version} has no icon: ${missing.join(', ')}`)
  const entries = [...ICON_NAMES].sort().map((name) => {
    const nodes = svgNodes(readFileSync(`${PKG}icons/${name}.svg`, 'utf8'))
    if (nodes.length === 0) throw new Error(`lucide-static ${version}: icon ${name} has no elements`)
    return `  '${name}': ${JSON.stringify(nodes)},`
  })
  const header = licence
    .replace(/\*\//g, '* /')
    .split('\n')
    .map((l) => (l ? ` * ${l}` : ' *'))
    .join('\n')
  const src = `/*
 * Lucide icons, vendored from lucide-static ${version} (https://lucide.dev). See THIRD_PARTY.md.
 *
${header}
 */
// Generated by scripts/vendor-icons.ts — do not edit; re-run the script instead.
import type { IconName } from '../../core/params/icon'

/** One SVG child element of a 24×24 Lucide icon: [tag, attributes]. */
export type IconNode = readonly (readonly [tag: string, attrs: Readonly<Record<string, string>>])[]

export const LUCIDE: Record<IconName, IconNode> = {
${entries.join('\n')}
}
`
  writeFileSync(OUT, src)
  console.log(`vendored ${entries.length} Lucide icons (lucide-static ${version}) → ${OUT}`)
}

main()
